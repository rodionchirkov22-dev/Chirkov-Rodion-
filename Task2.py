salary = 5000  # Ежемесячная зарплата
spend = 6000  # Траты за первый месяц
months = 10  # Количество месяцев, которое планируется протянуть без долгов
increase = 0.03  # Ежемесячный рост цен

# TODO Рассчитайте подушку безопасности, чтобы протянуть 10 месяцев без долгов

# Инициализируем необходимую подушку безопасности
money_needed = 0

# Рассчитываем необходимые средства для каждого месяца
for month in range(months):
    # Расходы в текущем месяце (в первый месяц без роста)
    current_spend = spend * ((1 + increase) ** month)

    # Недостаток средств после зарплаты
    deficit = current_spend - salary

    # Если есть дефицит, добавляем к необходимой подушке
    if deficit > 0:
        money_needed += deficit

# Округляем до целого числа
money_needed = round(money_needed)

print(f"Подушка безопасности, чтобы протянуть {months} месяцев без долгов:", money_needed)
